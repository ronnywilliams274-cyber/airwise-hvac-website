#!/usr/bin/env node
/* =====================================================================
   AIRWISE HVAC: download Pexels photos & videos into assets/media
   Cross-platform alternative to DOWNLOAD-MEDIA.bat (needs Node.js 18+):
     node tools/download-media.mjs
   Reads slots from assets/js/media-slots.js and the key from
   assets/js/config.js (or the PEXELS_API_KEY environment variable).
   ===================================================================== */
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'assets', 'media');

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(await fs.readFile(path.join(ROOT, 'assets/js/config.js'), 'utf8'), sandbox);
vm.runInContext(await fs.readFile(path.join(ROOT, 'assets/js/media-slots.js'), 'utf8'), sandbox);

const KEY = process.env.PEXELS_API_KEY || (sandbox.window.AIRWISE_CONFIG || {}).pexelsApiKey;
const SLOTS = sandbox.window.AIRWISE_MEDIA_SLOTS || {};
if (!KEY) { console.error('No Pexels API key. Set pexelsApiKey in assets/js/config.js or PEXELS_API_KEY.'); process.exit(1); }

const api = async (p) => {
  const r = await fetch('https://api.pexels.com' + p, { headers: { Authorization: KEY } });
  if (!r.ok) throw new Error(`Pexels HTTP ${r.status}`);
  return r.json();
};
const download = async (url, dest) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`download HTTP ${r.status}`);
  await fs.writeFile(dest, Buffer.from(await r.arrayBuffer()));
  return (await fs.stat(dest)).size;
};
const bestVideoFile = (v, target) => {
  const files = (v.video_files || []).filter((f) => f.link && f.width && String(f.file_type || '').includes('mp4')).sort((a, b) => a.width - b.width);
  if (!files.length) return null;
  return files.find((f) => f.width >= target * 0.7) || files[files.length - 1];
};

await fs.mkdir(OUT, { recursive: true });
const manifest = {};
let ok = 0, failed = 0;

for (const [name, slot] of Object.entries(SLOTS)) {
  const isVideo = slot.type === 'video';
  process.stdout.write(`\n-> ${name} (${slot.type})\n`);
  try {
    let item = null;
    if (slot.id) {
      try { item = await api(isVideo ? `/videos/videos/${slot.id}` : `/v1/photos/${slot.id}`); }
      catch { console.log(`   id ${slot.id} not available, falling back to search`); }
    }
    if (!item && slot.query) {
      const q = `?query=${encodeURIComponent(slot.query)}&per_page=15${slot.orientation ? '&orientation=' + slot.orientation : ''}`;
      const res = await api((isVideo ? '/videos/search' : '/v1/search') + q);
      let arr = (isVideo ? res.videos : res.photos) || [];
      if (isVideo) { const short = arr.filter((v) => v.duration >= 5 && v.duration <= 60); if (short.length) arr = short; }
      item = arr[Math.min(slot.pick || 0, arr.length - 1)] || null;
    }
    if (!item) throw new Error('nothing found');

    let dest, size;
    if (isVideo) {
      const f = bestVideoFile(item, slot.width || 1280);
      if (!f) throw new Error('no mp4 file in this video');
      dest = path.join(OUT, `${name}.mp4`);
      console.log(`   downloading ${f.width}x${f.height} video...`);
      size = await download(f.link, dest);
      let poster = '';
      if (item.image) { await download(item.image, path.join(OUT, `${name}-poster.jpg`)); poster = `assets/media/${name}-poster.jpg`; }
      manifest[name] = { type: 'video', src: `assets/media/${name}.mp4`, poster, alt: '', credit: { kind: 'Video', name: item.user?.name || 'Pexels', url: item.user?.url || item.url, page: item.url } };
    } else {
      const w = slot.orientation === 'portrait' ? 1000 : 1900;
      dest = path.join(OUT, `${name}.jpg`);
      size = await download(`${item.src.original}?auto=compress&cs=tinysrgb&w=${w}`, dest);
      manifest[name] = { type: 'photo', src: `assets/media/${name}.jpg`, poster: '', alt: item.alt || '', credit: { kind: 'Photo', name: item.photographer || 'Pexels', url: item.photographer_url || item.url, page: item.url } };
    }
    console.log(`   saved ${path.basename(dest)} (${(size / 1048576).toFixed(2)} MB)`);
    ok++;
  } catch (e) {
    console.log(`   skipped: ${e.message}`);
    failed++;
  }
}

const js = `/* Generated by download-media.mjs on ${new Date().toISOString().slice(0, 16).replace('T', ' ')}. Set to null to go back to live Pexels loading. */\nwindow.AIRWISE_LOCAL_MEDIA = ${JSON.stringify(manifest, null, 2)};\n`;
await fs.writeFile(path.join(OUT, 'media-local.js'), js);
console.log(`\nDone: ${ok} saved, ${failed} skipped. Media list written to assets/media/media-local.js`);
console.log("Before publishing, set  pexelsApiKey: ''  in assets/js/config.js so your key stays private.");
